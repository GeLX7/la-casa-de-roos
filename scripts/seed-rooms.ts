/**
 * Generates supabase/seed/admin_catalog_seed.sql from the static catalog in
 * src/data/listings.ts so the Supabase database starts with exactly the
 * content the live site shows today.
 *
 * Run with plain Node (>= 22.6 strips types natively, no deps needed):
 *
 *   node scripts/seed-rooms.ts
 *
 * The generated SQL is idempotent: rooms/ratings upsert by slug and the
 * repeatable child rows (features, notes, rules, images) are replaced
 * wholesale for the four seeded slugs only. Re-running it on a database the
 * owner has already edited will overwrite those rooms back to the static
 * content — only run it for the initial seed.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { listings } from "../src/data/listings.ts";
import { site } from "../src/data/site.ts";

const OUT_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "supabase",
  "seed",
  "admin_catalog_seed.sql",
);

/** The date the Airbnb figures in listings.ts were checked (see its header). */
const RATINGS_CHECKED_AT = "2026-06-10";

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;
const arr = (values: string[]) =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(", ")}]`;
const roomId = (slug: string) =>
  `(select id from public.rooms where slug = ${q(slug)})`;

/** Env var that will hold the room's private Airbnb iCal URL (matches src/lib/booking/config.ts). */
const icalEnvKey = (slug: string) =>
  `AIRBNB_ICAL_${slug.toUpperCase().replace(/-/g, "_")}`;

const slugs = listings.map((l) => l.slug);
const slugList = slugs.map(q).join(", ");

const lines: string[] = [
  "-- Generated by scripts/seed-rooms.ts — do not edit by hand.",
  "-- Seeds the admin catalog with the current static content from src/data/listings.ts.",
  "-- Idempotent for the four seeded slugs, but it OVERWRITES owner edits to them;",
  "-- run once during initial setup (docs/runbooks/admin-supabase-setup.md).",
  "",
  "begin;",
  "",
];

// Rooms ----------------------------------------------------------------------
for (const [index, l] of listings.entries()) {
  lines.push(
    `insert into public.rooms (slug, name, airbnb_url, active, subtitle, airbnb_listing_id, capacity, beds, bath, checkin, checkout, quiet_hours, description_title, short_description, long_description, price_label, guest_favorite, sort_order)`,
    `values (`,
    `  ${q(l.slug)},`,
    `  ${q(l.title)},`,
    `  ${q(l.airbnbUrl)},`,
    `  true,`,
    `  ${q(l.subtitle)},`,
    `  ${q(l.airbnbListingId)},`,
    `  ${l.capacity},`,
    `  ${q(l.beds)},`,
    `  ${q(l.bath)},`,
    `  ${q(site.checkin)},`,
    `  ${q(site.checkout)},`,
    `  ${q(l.quietHours)},`,
    `  'La suite',`,
    `  ${q(l.shortDescription)},`,
    `  ${arr(l.longDescription)},`,
    `  ${q(l.priceLabel)},`,
    `  ${l.guestFavorite},`,
    `  ${index}`,
    `)`,
    `on conflict (slug) do update set`,
    `  name = excluded.name,`,
    `  airbnb_url = excluded.airbnb_url,`,
    `  subtitle = excluded.subtitle,`,
    `  airbnb_listing_id = excluded.airbnb_listing_id,`,
    `  capacity = excluded.capacity,`,
    `  beds = excluded.beds,`,
    `  bath = excluded.bath,`,
    `  checkin = excluded.checkin,`,
    `  checkout = excluded.checkout,`,
    `  quiet_hours = excluded.quiet_hours,`,
    `  description_title = excluded.description_title,`,
    `  short_description = excluded.short_description,`,
    `  long_description = excluded.long_description,`,
    `  price_label = excluded.price_label,`,
    `  guest_favorite = excluded.guest_favorite,`,
    `  sort_order = excluded.sort_order,`,
    `  updated_at = now();`,
    "",
  );
}

// Repeatable child content (replace wholesale for the seeded slugs) -----------
lines.push(
  `delete from public.room_features where room_id in (select id from public.rooms where slug in (${slugList}));`,
  `delete from public.room_not_included where room_id in (select id from public.rooms where slug in (${slugList}));`,
  `delete from public.room_rules where room_id in (select id from public.rooms where slug in (${slugList}));`,
  `delete from public.room_images where room_id in (select id from public.rooms where slug in (${slugList}));`,
  "",
);

for (const l of listings) {
  for (const [i, a] of l.amenities.entries()) {
    lines.push(
      `insert into public.room_features (room_id, icon, label, enabled, sort_order) values (${roomId(l.slug)}, ${q(a.icon)}, ${q(a.label)}, true, ${i});`,
    );
  }
  for (const [i, n] of l.notIncluded.entries()) {
    lines.push(
      `insert into public.room_not_included (room_id, label, enabled, sort_order) values (${roomId(l.slug)}, ${q(n)}, true, ${i});`,
    );
  }
  for (const [i, r] of l.rules.entries()) {
    lines.push(
      `insert into public.room_rules (room_id, label, enabled, sort_order) values (${roomId(l.slug)}, ${q(r)}, true, ${i});`,
    );
  }
  for (const [i, p] of l.gallery.entries()) {
    lines.push(
      `insert into public.room_images (room_id, src, alt, category, is_cover, active, sort_order) values (${roomId(l.slug)}, ${q(p.src)}, ${q(p.alt)}, ${q(p.category)}, ${i === 0}, true, ${i});`,
    );
  }
  lines.push("");
}

// Ratings ----------------------------------------------------------------------
for (const l of listings) {
  const c = l.categoryRatings;
  lines.push(
    `insert into public.room_ratings (room_id, rating, review_count, cleanliness, accuracy, checkin, communication, location, value, source, checked_at)`,
    `values (${roomId(l.slug)}, ${l.rating}, ${l.reviewCount}, ${c.cleanliness}, ${c.accuracy}, ${c.checkin}, ${c.communication}, ${c.location}, ${c.value}, 'airbnb', '${RATINGS_CHECKED_AT}')`,
    `on conflict (room_id) do update set`,
    `  rating = excluded.rating,`,
    `  review_count = excluded.review_count,`,
    `  cleanliness = excluded.cleanliness,`,
    `  accuracy = excluded.accuracy,`,
    `  checkin = excluded.checkin,`,
    `  communication = excluded.communication,`,
    `  location = excluded.location,`,
    `  value = excluded.value,`,
    `  checked_at = excluded.checked_at,`,
    `  updated_at = now();`,
    "",
  );
}

// Calendar sources (env key references only — never the private URLs) ---------
for (const l of listings) {
  lines.push(
    `insert into public.calendar_sources (room_id, provider, ical_url_encrypted_or_env_key, active)`,
    `values (${roomId(l.slug)}, 'airbnb', ${q(icalEnvKey(l.slug))}, true)`,
    `on conflict (room_id, provider) do update set`,
    `  ical_url_encrypted_or_env_key = excluded.ical_url_encrypted_or_env_key,`,
    `  active = excluded.active,`,
    `  updated_at = now();`,
    "",
  );
}

lines.push("commit;", "");

writeFileSync(OUT_PATH, lines.join("\n"));
console.log(`Wrote ${OUT_PATH}`);
